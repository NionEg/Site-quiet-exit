export const allLessons: Lesson[] = blocks.flatMap((bl) => bl.lessons);

export const lessonById = new Map(allLessons.map((l) => [l.id, l]));

export const TOTAL_LESSONS = allLessons.length;

export function nextLesson(id: string): Lesson | null {
  const i = allLessons.findIndex((l) => l.id === id);
  return i >= 0 && i < allLessons.length - 1 ? allLessons[i + 1] : null;
}

export function prevLesson(id: string): Lesson | null {
  const i = allLessons.findIndex((l) => l.id === id);
  return i > 0 ? allLessons[i - 1] : null;
}
